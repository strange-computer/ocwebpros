/**
 * Re-render + optionally upload city videos from video-manifest.json
 *
 * Usage:
 *   node scripts/batch-city-videos.mjs
 *   node scripts/batch-city-videos.mjs --skip-upload
 *   node scripts/batch-city-videos.mjs --missing-only --skip-upload
 *   node scripts/batch-city-videos.mjs --only tustin,brea --skip-upload
 */
import { createReadStream, mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { getRoot, loadEnv } from './lib/env.mjs';
import { renderPageVideo } from './lib/render-page-video.mjs';
import { getAuthorizedClient, getYoutube } from './lib/youtube.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = getRoot();

function parseArgs(argv) {
  const out = { only: null, skipUpload: false, missingOnly: false, skipExistingFile: false };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--skip-upload') out.skipUpload = true;
    else if (argv[i] === '--missing-only') out.missingOnly = true;
    else if (argv[i] === '--skip-existing-file') out.skipExistingFile = true;
    else if (argv[i] === '--only') out.only = argv[++i];
  }
  return out;
}

const cli = parseArgs(process.argv.slice(2));
loadEnv();

const resultsPath = join(root, 'src', 'data', 'cityVideos.ts');
const jsonRecordPath = join(root, 'tmp', 'youtube-uploads', 'city-batch-results.json');

function loadExistingCityVideos() {
  if (!existsSync(resultsPath)) return {};
  const text = readFileSync(resultsPath, 'utf8');
  const map = {};
  const blockRe = /['"]?([a-z0-9-]+)['"]?:\s*\{([\s\S]*?)\n  \},?/g;
  let m;
  while ((m = blockRe.exec(text))) {
    const slug = m[1];
    if (slug === 'export' || slug === 'interface') continue;
    const body = m[2];
    const youtubeId = body.match(/youtubeId:\s*'([^']+)'/)?.[1];
    const title = body.match(/title:\s*('(?:\\'|[^'])*'|"(?:\\"|[^"])*")/)?.[1];
    const localSrc = body.match(/localSrc:\s*'([^']+)'/)?.[1];
    let parsedTitle = title;
    try {
      parsedTitle = title ? JSON.parse(title.replace(/^'/, '"').replace(/'$/, '"')) : slug;
    } catch {
      parsedTitle = title?.replace(/^['"]|['"]$/g, '') || slug;
    }
    if (youtubeId || localSrc) {
      map[slug] = { youtubeId, title: parsedTitle, localSrc };
    }
  }
  return map;
}

let manifest = JSON.parse(readFileSync(join(__dirname, 'video-manifest.json'), 'utf8'));
const existing = loadExistingCityVideos();

if (cli.only) {
  const wanted = new Set(cli.only.split(',').map((s) => s.trim()).filter(Boolean));
  manifest = manifest.filter(
    (item) => wanted.has(item.id) || wanted.has(item.citySlug) || wanted.has(item.id.replace(/^local-seo-/, '')),
  );
}

if (cli.missingOnly) {
  manifest = manifest.filter((item) => {
    const meta = existing[item.citySlug];
    const mp4 = join(root, 'public', 'videos', 'pages', `${item.id}.mp4`);
    return !meta && !existsSync(mp4);
  });
}

async function uploadVideo(youtube, item, filePath) {
  const response = await youtube.videos.insert({
    part: ['snippet', 'status'],
    requestBody: {
      snippet: {
        title: item.title.slice(0, 100),
        description: [
          item.script,
          '',
          `Landmarks: ${(item.landmarks || []).join(', ')}`,
          `Page: https://ocwebpros.com/${item.slug}/`,
          '',
          'OCWebPros — Lake Forest, CA local SEO.',
        ].join('\n'),
        tags: ['local seo', item.citySlug, 'orange county', 'ocwebpros', 'google maps'],
        categoryId: '27',
      },
      status: {
        privacyStatus: 'unlisted',
        selfDeclaredMadeForKids: false,
      },
    },
    media: { body: createReadStream(filePath) },
  });
  return response.data.id;
}

function writeCityVideosTs(map) {
  const lines = [
    '/** Auto-generated by scripts/batch-city-videos.mjs */',
    'export interface CityVideoMeta {',
    '  youtubeId?: string;',
    '  title: string;',
    '  url?: string;',
    '  localSrc?: string;',
    '}',
    '',
    '/** YouTube / local embeds for /local-seo/{city}/ pages */',
    'export const cityLocalSeoVideos: Record<string, CityVideoMeta> = {',
  ];

  for (const slug of Object.keys(map).sort()) {
    const meta = map[slug];
    if (!meta?.youtubeId && !meta?.localSrc) continue;
    lines.push(`  '${slug}': {`);
    if (meta.youtubeId) lines.push(`    youtubeId: '${meta.youtubeId}',`);
    lines.push(`    title: ${JSON.stringify(meta.title)},`);
    if (meta.youtubeId) lines.push(`    url: 'https://www.youtube.com/watch?v=${meta.youtubeId}',`);
    lines.push(`    localSrc: ${JSON.stringify(meta.localSrc || `/videos/pages/local-seo-${slug}.mp4`)},`);
    lines.push('  },');
  }

  lines.push('};');
  lines.push('');
  writeFileSync(resultsPath, lines.join('\n'), 'utf8');
}

async function main() {
  if (!manifest.length) {
    console.log('Nothing to process.');
    return;
  }

  console.log(`\n🎬 City batch: ${manifest.length} videos`);
  console.log(`   upload: ${cli.skipUpload ? 'no' : 'yes (unlisted)'}\n`);

  let youtube = null;
  if (!cli.skipUpload) {
    const auth = await getAuthorizedClient();
    youtube = getYoutube(auth);
  }

  const merged = { ...existing };
  const records = [];

  for (const [index, item] of manifest.entries()) {
    console.log(`\n[${index + 1}/${manifest.length}] ${item.id}`);
    if (index > 0) {
      await new Promise((r) => setTimeout(r, 2500));
    }
    try {
      const rendered = await renderPageVideo(item, {
        skipIfExists: Boolean(cli.skipExistingFile),
      });
      console.log(`  mp4: ${rendered.outMp4}${rendered.skipped ? ' (cached)' : ''}`);

      let youtubeId = existing[item.citySlug]?.youtubeId || null;
      if (!cli.skipUpload) {
        try {
          console.log('  uploading to YouTube…');
          youtubeId = await uploadVideo(youtube, item, rendered.outMp4);
          console.log(`  ✅ https://www.youtube.com/watch?v=${youtubeId}`);
        } catch (uploadErr) {
          console.error(`  ⚠ YouTube upload skipped: ${uploadErr.message}`);
        }
      }

      const localSrc = `/videos/pages/${item.id}.mp4`;
      merged[item.citySlug] = {
        youtubeId: youtubeId || undefined,
        title: item.title,
        localSrc,
      };

      records.push({
        id: item.id,
        citySlug: item.citySlug,
        title: item.title,
        youtubeId,
        localSrc,
        uploadedAt: new Date().toISOString(),
      });
    } catch (error) {
      console.error(`  ❌ ${error.message}`);
      records.push({ id: item.id, citySlug: item.citySlug, title: item.title, error: error.message });
    }
  }

  mkdirSync(dirname(jsonRecordPath), { recursive: true });
  writeFileSync(jsonRecordPath, JSON.stringify(records, null, 2), 'utf8');
  writeCityVideosTs(merged);

  const ok = records.filter((r) => r.localSrc && !r.error);
  console.log(`\n📝 Wrote ${resultsPath}`);
  console.log(`Done. ${ok.length}/${manifest.length} rendered (local embeds ready).`);
  console.log(`YouTube ids: ${records.filter((r) => r.youtubeId).length}\n`);
  if (ok.length < manifest.length) process.exitCode = 1;
}

main().catch((error) => {
  console.error('\n❌ Batch failed:', error.message);
  process.exit(1);
});
